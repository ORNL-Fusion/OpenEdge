#!/usr/bin/env python3
"""input/srate.deck and 3d/input/srate_3d.deck: the measured shot-14449 Li source
(input/14449_source_rate.csv, atoms/s vs shot time) as a 20 ms staircase of
macro-grains per emission event, `variable srate`, for `fix particulate/emit ... n v_srate`.
2-D: sim t = 0 corresponds to CSV t = T0_MS.  3-D: the CSV is the Li released into the plasma, so the
grains are emitted T_FALL_MS earlier (sim t = 0 at shot -T_FALL_MS): the 3-D staircase starts at CSV 0.
n = S * NEVERY*DT / (ATOMS_PER_GRAIN * NWEIGHT)."""
import math
from pathlib import Path
import numpy as np

ROOT = Path(__file__).resolve().parents[1]
CSV = ROOT / "input/14449_source_rate.csv"
DT, NEVERY = 2.0e-6, 200                     # must match in.openedge
NSTEPS, BLOCK_MS, T0_MS = 250000, 20, 40.0
T0_3D_MS, T_FALL_MS = 0.0, 150.0               # 3-D: CSV time of sim t = 0; grain fall time
R_GRAIN, RHO_LI, NWEIGHT = 25e-6, 534.0, 80   # must match input/grains_r25.species and the deck
ATOMS_PER_GRAIN = (4 / 3 * math.pi * R_GRAIN**3 * RHO_LI) / (6.941 * 1.66053906660e-27)


def staircase(t, s, T0_MS, note=""):
    terms, n_events = [], []
    for k in range(0, int(NSTEPS * DT * 1e3), BLOCK_MS):
        s0, s1 = int(k * 1e-3 / DT), int((k + BLOCK_MS) * 1e-3 / DT)
        sel = (t >= T0_MS + k) & (t < T0_MS + k + BLOCK_MS)
        S = s[sel].mean() if sel.any() else 0.0
        n = S * NEVERY * DT / (ATOMS_PER_GRAIN * NWEIGHT)
        n_events.append(n)
        terms.append(f"(step>={s0})*(step<{s1})*{n:.2f}")
    srate = "+".join(terms) + "+1e-6"
    head = ("# generated by make_srate.py — do not edit by hand\n"
            f"# shot 14449 S(t) from {CSV.name}, {len(terms)} x {BLOCK_MS} ms blocks, "
            f"peak feed {max(n_events) * NWEIGHT * ATOMS_PER_GRAIN / (NEVERY * DT):.2e} atoms/s, "
            f"r {R_GRAIN*1e6:.0f} um x nweight {NWEIGHT}\n" + note)
    return head + f"# use with: -var nsrc v_srate -var nweight {NWEIGHT} -var nsteps {NSTEPS}\n" \
                  f"variable    srate equal {srate}\n", n_events


def main():
    t, s = np.loadtxt(CSV, delimiter=",", comments="#", unpack=True)
    body, n_events = staircase(t, s, T0_MS)
    (ROOT / "input/srate.deck").write_text(body)
    body3, _ = staircase(t, s, T0_3D_MS, f"# 3-D: grains emitted {T_FALL_MS:.0f} ms before the CSV Li release: sim t = 0 is shot -{T_FALL_MS:.0f} ms\n")
    (ROOT / "3d/input/srate_3d.deck").write_text(body3)
    print(f"wrote srate.deck (CSV from {T0_MS:g} ms) and 3d/input/srate_3d.deck (CSV from {T0_3D_MS:g} ms), "
          f"n/event {min(n_events):.2f}..{max(n_events):.2f}")


if __name__ == "__main__":
    main()
